-- Jalankan skrip ini di menu SQL Editor Supabase (Proyek: kelontong)

create table if not exists public.produk (
  id bigint generated by default as identity primary key,
  nama text not null,
  kategori text not null,
  harga integer not null,
  satuan text not null,
  status text not null default 'Ready',
  foto_url text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.produk enable row level security;

drop policy if exists "Publik bisa lihat produk" on public.produk;
create policy "Publik bisa lihat produk"
on public.produk for select
using (true);

drop policy if exists "Hanya admin bisa kelola produk" on public.produk;
create policy "Hanya admin bisa kelola produk"
on public.produk for all
to authenticated
using (true)
with check (true);
