-- =========================================================
-- Skrip Setup Database Toko Kelontong
-- Jalankan skrip ini di menu SQL Editor Supabase (Proyek: kelontong)
-- =========================================================

-- 1. Buat Tabel Produk
create table if not exists public.produk (
  id bigint generated by default as identity primary key,
  nama text not null,
  kategori text not null,
  harga integer not null,
  satuan text not null,
  status text not null default 'Ready',
  foto_url text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Berikan Izin Akses Tabel ke Role Supabase (anon & authenticated)
grant usage on schema public to anon, authenticated;
grant select on public.produk to anon;
grant all on public.produk to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- 3. Aktifkan Row Level Security (RLS)
alter table public.produk enable row level security;

-- 4. Kebijakan RLS: Publik hanya boleh melihat data (SELECT)
drop policy if exists "Publik bisa lihat produk" on public.produk;
create policy "Publik bisa lihat produk"
on public.produk for select
to anon, authenticated
using (true);

-- 5. Kebijakan RLS: Hanya user yang login (Admin) yang bisa tambah/edit/hapus
drop policy if exists "Hanya admin bisa kelola produk" on public.produk;
create policy "Hanya admin bisa kelola produk"
on public.produk for all
to authenticated
using (true)
with check (true);
